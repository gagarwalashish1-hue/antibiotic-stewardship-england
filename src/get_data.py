"""
get_data.py  -  Step 1: download the data this project uses.

What it does
  1. Asks the NHSBSA Open Data Portal API for 12 months of antibacterial
     prescribing (BNF chapter 5.1), already added up per GP practice and month,
     and grouped by UK-AWaRe using data/aware_mapping.csv.
     -> data/raw/abx_12m_practice_month.csv   (about 94,000 rows, ~10 MB)
  2. Downloads the "Patients registered at a GP practice" totals file for
     each month from NHS England Digital.
     -> data/raw/lists/list_YYYY-MM.csv

Why use the API instead of the website download?
  One month of the full prescribing file is about 7.8 GB (18.6 million rows).
  The API lets the NHSBSA server do the filtering and adding-up, so we only
  download the ~8,000 rows per month we actually need.

  3. A second query (POST) for the same months: dose-based usage (ADQ) by UK-AWaRe
     group and items for each Watch substance, per practice.
     -> data/raw/abx_12m_adq_watchdrug.csv
  4. Writes the exact SQL text of both queries to sql/ (generated from
     data/aware_mapping.csv, so the code lists can never drift apart).

Run from the repo root:  python src/get_data.py
Needs: pandas, requests   (pip install pandas requests)
"""
import io, os, re, time, zipfile
import pandas as pd
import requests

MONTHS = ["202509", "202510", "202511", "202512", "202601", "202602",
          "202603", "202604", "202605", "202606", "202607", "202608"]
API = "https://opendata.nhsbsa.net/api/3/action/datastore_search_sql"
LIST_PAGE = "https://digital.nhs.uk/data-and-information/publications/statistical/patients-registered-at-a-gp-practice/{}"
MONTH_NAMES = ["january", "february", "march", "april", "may", "june", "july",
               "august", "september", "october", "november", "december"]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.makedirs(f"{ROOT}/data/raw/lists", exist_ok=True)
mapping = pd.read_csv(f"{ROOT}/data/aware_mapping.csv")


def codes(group):
    """Return the BNF substance codes in one UK-AWaRe group as  'a','b','c'  for SQL."""
    c = mapping.loc[mapping.AWARE_GROUP == group, "BNF_CHEMICAL_SUBSTANCE_CODE"]
    return ",".join(f"'{x}'" for x in c)


def cols(table):
    """Column names changed in March 2025: before then the substance code is BNF_CHEMICAL_SUBSTANCE,
    the presentation code BNF_CODE and dose usage ADQUSAGE. ADQ_USAGE is text in some months, so it is cast."""
    old = int(table[-6:]) < 202503
    return (("BNF_CHEMICAL_SUBSTANCE", "BNF_CODE", "ADQUSAGE") if old else
            ("BNF_CHEMICAL_SUBSTANCE_CODE", "BNF_PRESENTATION_CODE", "SAFE_CAST(ADQ_USAGE AS FLOAT64)"))


def build_sql(table):
    """One SQL query: antibacterials only, UNIDENTIFIED removed, one row per practice."""
    S, B, _ = cols(table)
    sums = ",\n  ".join(
        f"sum(CASE WHEN {S} IN ({codes(g)}) THEN ITEMS ELSE 0 END) {g.lower()}_items"
        for g in ["Access", "Watch", "Reserve", "Other"])
    return f"""SELECT YEAR_MONTH ym, PRACTICE_CODE pc, max(PRACTICE_NAME) pn, max(ICB_NAME) icb,
  sum(ITEMS) all_items,
  {sums},
  sum(CASE WHEN {S}='0501030L0' THEN ITEMS ELSE 0 END) lyme_items
FROM `{table}`
WHERE {B} LIKE '0501%' AND UNIDENTIFIED <> 'Y'
GROUP BY YEAR_MONTH, PRACTICE_CODE"""


def build_sql_adq(table):
    """Second query: ADQ by UK-AWaRe group and items per Watch substance, one row per practice."""
    S, B, A = cols(table)
    adq = ",\n  ".join(
        f"sum(CASE WHEN {S} IN ({codes(g)}) THEN {A} ELSE 0 END) adq_{g[0]}"
        for g in ["Access", "Watch", "Reserve", "Other"])
    watch = mapping.loc[mapping.AWARE_GROUP == "Watch", "BNF_CHEMICAL_SUBSTANCE_CODE"]
    items = ",\n  ".join(f"sum(CASE WHEN {S}='{c}' THEN ITEMS ELSE 0 END) w_{c}" for c in watch)
    return f"""SELECT PRACTICE_CODE pc,
  sum({A}) adq_all,
  {adq},
  sum(CASE WHEN {S}='0501030L0' THEN {A} ELSE 0 END) adq_lyme,
  {items}
FROM `{table}`
WHERE {B} LIKE '0501%' AND UNIDENTIFIED <> 'Y'
GROUP BY PRACTICE_CODE"""


HEADER = ("-- Generated by src/get_data.py from data/aware_mapping.csv. Do not edit by hand.\n"
          "-- Sent to {api} as a POST with body {{resource_id, sql}}, once for each month\n"
          "-- EPD_SNOMED_202509 ... EPD_SNOMED_202608 (src/get_data.py loops over the months).\n"
          "-- Shown here for July 2026.\n\n")


def write_sql():
    os.makedirs("sql", exist_ok=True)
    open("sql/nhsbsa_api_query.sql", "w").write(HEADER.format(api=API) + build_sql("EPD_SNOMED_202607") + "\n")
    open("sql/nhsbsa_adq_and_watch_drugs.sql", "w").write(HEADER.format(api=API) + build_sql_adq("EPD_SNOMED_202607") + "\n")


def post_sql(table, sql):
    r = requests.post(API, json={"resource_id": table, "sql": sql}, timeout=300)
    r.raise_for_status()
    return r.json()["result"]["result"]["records"]


def get_adq(months=MONTHS, out="data/raw"):
    frames = []
    for m in months:
        recs = post_sql(f"EPD_SNOMED_{m}", build_sql_adq(f"EPD_SNOMED_{m}"))
        frames.append(pd.DataFrame(recs).assign(ym=m)); time.sleep(1)
    df = pd.concat(frames)
    df[["ym"] + [c for c in df.columns if c != "ym"]].to_csv(f"{out}/abx_12m_adq_watchdrug.csv", index=False)


def get_prescribing(months=MONTHS, out="data/raw"):
    frames = []
    for m in months:
        table = f"EPD_SNOMED_{m}"
        recs = post_sql(table, build_sql(table))
        print(f"  {m}: {len(recs):,} practices")
        frames.append(pd.DataFrame(recs))
        time.sleep(1)  # be polite to the server
    cols_ = ["ym", "pc", "pn", "icb", "all_items", "access_items", "watch_items",
            "reserve_items", "other_items", "lyme_items"]
    d = pd.concat(frames)[cols_]
    ym = d.ym.astype(str).str.replace(r"\D", "", regex=True)   # API gives 202409 in older months, 2025-03 in newer ones
    d["ym"] = ym.str[:4] + "-" + ym.str[4:6]
    d.to_csv(f"{out}/abx_12m_practice_month.csv", index=False)


def get_list_sizes(months=("202509", "202512", "202603", "202604", "202607"), out="data/raw/lists"):
    os.makedirs(out, exist_ok=True)
    for m in months:
        y, mo = m[:4], int(m[4:])
        page = requests.get(LIST_PAGE.format(f"{MONTH_NAMES[mo-1]}-{y}"), timeout=60).text
        link = re.search(r"https://files\.digital\.nhs\.uk/[^\"']*gp-reg-pat-prac-all\.(zip|csv)", page)
        if not link:
            print(f"  {m}: totals file not found on page, skipping"); continue
        raw = requests.get(link.group(0), timeout=120).content
        if link.group(0).endswith(".zip"):
            with zipfile.ZipFile(io.BytesIO(raw)) as z:
                raw = z.read([n for n in z.namelist() if n.endswith(".csv")][0])
        dest = f"{out}/list_{y}-{m[4:]}.csv"
        open(dest, "wb").write(raw)
        print(f"  {m}: saved {dest}")


MONTHS_Y0 = ["202309", "202310", "202311", "202312", "202401", "202402",
             "202403", "202404", "202405", "202406", "202407", "202408"]   # third year: items only, no dose query needed
MONTHS_Y1 = ["202409", "202410", "202411", "202412", "202501", "202502",
             "202503", "202504", "202505", "202506", "202507", "202508"]
QOF = {"2526": "https://files.digital.nhs.uk/05/37C52B/QOF_2526_v2.zip"}   # raw data .csv files, NHS England Digital


def get_qof():
    for yr, url in QOF.items():
        with zipfile.ZipFile(io.BytesIO(requests.get(url, timeout=300).content)) as z:
            z.extract(f"PREVALENCE_{yr}.csv", f"data/raw/qof/{yr}")       # only the prevalence file is used
        print(f"  QOF {yr}: saved data/raw/qof/{yr}")


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    write_sql()
    print("Prescribing (NHSBSA API)..."); get_prescribing()
    print("Dose (ADQ) and Watch substances (NHSBSA API)..."); get_adq()
    print("Patient list sizes (NHS England Digital)..."); get_list_sizes()
    os.makedirs("data/raw/y2425", exist_ok=True)
    print("Second year, Sep 2024 - Aug 2025..."); get_prescribing(MONTHS_Y1, "data/raw/y2425"); get_adq(MONTHS_Y1, "data/raw/y2425")
    get_list_sizes(("202409", "202412", "202503", "202504", "202507"), "data/raw/y2425/lists")
    os.makedirs("data/raw/y2324", exist_ok=True)
    print("Third year, Sep 2023 - Aug 2024..."); get_prescribing(MONTHS_Y0, "data/raw/y2324")
    get_list_sizes(("202309", "202312", "202403", "202404", "202407"), "data/raw/y2324/lists")
    print("QOF disease registers..."); get_qof()
    print("Done. Age bands: download 'gp-reg-pat-prac-quin-age' (July 2026) by hand into data/raw/ - see README.")
